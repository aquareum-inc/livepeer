import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { describe, expect, it, vi } from "vitest";

vi.mock("server-only", () => ({}));

const { canonical, confirmMessage, inputHash, unlockMessage } = await import("./proof");

/**
 * The values the native apps' own tests check their hashing and message building against, so a phone and
 * the instance can't come to disagree about what is signed. Refresh the file after a deliberate change with
 * `WRITE_VECTORS=1 corepack pnpm --filter @livepeer/web test vectors`.
 */
const file = path.resolve(import.meta.dirname, "../../../../docs/mobile/fixtures/operator_proof_vectors.json");

const INPUTS: Array<Record<string, unknown>> = [
  { id: "rep_8Jk2", outcome: "hidden" },
  { outcome: "dismissed", id: "rep_8Jk2" },
  { id: "usr_demo_priya", status: "paused" },
  { status: "active", id: "usr_demo_priya", tenant_id: "default" },
  { id: "usr \"quoted\" / ünïcode \n line", status: "paused" },
  {},
  // A list keeps the order it was given: turning alerts on, and turning them off.
  { push_token: "5a".repeat(32), kinds: ["engine_not_ready", "reports_waiting"], environment: "development" },
  { kinds: [] },
];
const NONCE = "q0hY0mVtQ3v1c1m7m5mJf2J8h1b5V8l2r9x3X6n4u0A";

const vectors = {
  about: "Generated by apps/web/lib/operator-devices/vectors.test.ts. An input hash is base64url(SHA-256(canonical)) with no padding; a signature is ECDSA P-256 over SHA-256 of the message's UTF-8 bytes, DER, base64url.",
  inputs: INPUTS.map((input) => ({ input, canonical: canonical(input), hash: inputHash(input) })),
  messages: {
    unlock: { nonce: NONCE, message: unlockMessage(NONCE) },
    confirm: { nonce: NONCE, operation: "operator_resolve_report", input_hash: inputHash(INPUTS[0]!), message: confirmMessage(NONCE, "operator_resolve_report", inputHash(INPUTS[0]!)) },
  },
  proof_header: { name: "X-Operator-Proof", value: "<nonce>.<signature>" },
};

describe("operator proof vectors", () => {
  it("are what docs/mobile/fixtures holds for the native apps", () => {
    if (process.env.WRITE_VECTORS === "1") writeFileSync(file, `${JSON.stringify(vectors, null, 2)}\n`);
    expect(JSON.parse(readFileSync(file, "utf8"))).toEqual(vectors);
  });

  it("put keys in order and leave nothing to a serialiser's taste", () => {
    expect(vectors.inputs[0]!.canonical).toBe('{"id":"rep_8Jk2","outcome":"hidden"}');
    expect(vectors.inputs[3]!.canonical).toBe('{"id":"usr_demo_priya","status":"active","tenant_id":"default"}');
    expect(vectors.inputs[5]!.canonical).toBe("{}");
    expect(vectors.inputs[6]!.canonical).toBe(`{"environment":"development","kinds":["engine_not_ready","reports_waiting"],"push_token":"${"5a".repeat(32)}"}`);
    expect(vectors.inputs[7]!.canonical).toBe('{"kinds":[]}');
    expect(vectors.messages.confirm.message.split("\n")).toEqual(["livepeer-operator-confirm", NONCE, "operator_resolve_report", vectors.inputs[0]!.hash]);
  });
});
